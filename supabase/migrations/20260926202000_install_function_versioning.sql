create or replace function archive.redact_function_source(p_source text)
returns text
language sql
immutable
as $function$
  select regexp_replace(
    regexp_replace(
      regexp_replace(
        coalesce(p_source, ''),
        '[0-9]{7,12}:[A-Za-z0-9_-]{25,}',
        '<REDACTED_LEGACY_TELEGRAM_BOT_TOKEN>',
        'g'
      ),
      'sb_secret_[A-Za-z0-9_-]{10,}',
      '<REDACTED_SUPABASE_SECRET_KEY>',
      'g'
    ),
    'eyJ[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{20,}',
    '<REDACTED_JWT>',
    'g'
  );
$function$;

create or replace function public.get_function_publish_payload(
  p_function_history_id bigint,
  p_publish_token uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_schema text;
  v_function_name text;
  v_payload jsonb;
begin
  if not exists (
    select 1
    from archive.github_push_queue q
    where q.function_history_id = p_function_history_id
      and q.publish_token = p_publish_token
      and q.status = 'pending'
      and q.try_count < 10
  ) then
    raise exception 'invalid or inactive publish token'
      using errcode = '42501';
  end if;

  select fh.schema_name, fh.function_name
  into v_schema, v_function_name
  from archive.function_history fh
  where fh.id = p_function_history_id;

  if v_schema is null or v_function_name is null then
    raise exception 'function history row not found'
      using errcode = 'P0002';
  end if;

  select jsonb_build_object(
    'schema', v_schema,
    'function_name', v_function_name,
    'overloads', coalesce(
      jsonb_agg(
        jsonb_build_object(
          'language', fh.lang_settings,
          'args', fh.args,
          'return_type', fh.return_type,
          'source_code', archive.redact_function_source(fh.source_code)
        )
        order by fh.lang_settings, fh.args, fh.return_type
      ),
      '[]'::jsonb
    )
  )
  into v_payload
  from archive.function_history fh
  where fh.schema_name = v_schema
    and fh.function_name = v_function_name
    and fh.active = true;

  return v_payload;
end;
$function$;

revoke all on function public.get_function_publish_payload(bigint, uuid)
from public, anon, authenticated;
grant execute on function public.get_function_publish_payload(bigint, uuid)
to service_role;

create or replace function archive.github_send_function(
  p_function_history_id bigint
)
returns void
language plpgsql
as $function$
declare
  v_publish_token uuid;
  v_edge_base_url text;
  v_response extensions.http_response;
  v_body jsonb;
begin
  select q.publish_token
  into v_publish_token
  from archive.github_push_queue q
  where q.function_history_id = p_function_history_id
    and q.status = 'pending';

  if v_publish_token is null then
    raise exception 'pending queue item not found';
  end if;

  select edge_base_url
  into v_edge_base_url
  from archive.function_versioning_settings
  where singleton = true;

  if v_edge_base_url is null then
    raise exception 'function versioning edge_base_url is not configured';
  end if;

  v_response := extensions.http((
    'POST',
    rtrim(v_edge_base_url, '/') || '/github-send',
    array[
      extensions.http_header('Content-Type', 'application/json')
    ],
    'application/json',
    jsonb_build_object(
      'function_history_id', p_function_history_id,
      'publish_token', v_publish_token
    )::text
  )::extensions.http_request);

  if v_response.status < 200 or v_response.status >= 300 then
    raise exception
      'github-send HTTP %: %',
      v_response.status,
      left(coalesce(v_response.content, ''), 1000);
  end if;

  v_body := v_response.content::jsonb;

  if coalesce((v_body->>'ok')::boolean, false) is not true then
    raise exception
      'github-send failed: %',
      coalesce(v_body->>'error', v_response.content);
  end if;
end;
$function$;

create or replace function archive.process_github_push_queue(
  p_limit integer default 5
)
returns integer
language plpgsql
as $function$
declare
  r record;
  v_count integer := 0;
begin
  for r in
    select id, function_history_id, try_count
    from archive.github_push_queue
    where status = 'pending'
      and try_count < 10
    order by id
    limit greatest(p_limit, 0)
    for update skip locked
  loop
    begin
      perform archive.github_send_function(r.function_history_id);

      update archive.github_push_queue
      set status = 'done',
          pushed_at = now(),
          last_error = null
      where id = r.id;

      v_count := v_count + 1;
    exception when others then
      update archive.github_push_queue
      set try_count = try_count + 1,
          last_error = SQLERRM,
          status = case
            when try_count + 1 >= 10 then 'dead'
            else 'pending'
          end
      where id = r.id;
    end;
  end loop;

  return v_count;
end;
$function$;

create or replace function archive.github_push_queue_summary()
returns table(
  status text,
  item_count bigint,
  min_created_at timestamptz,
  max_created_at timestamptz,
  max_try_count integer
)
language sql
stable
as $function$
  select
    q.status,
    count(*),
    min(q.created_at),
    max(q.created_at),
    max(q.try_count)
  from archive.github_push_queue q
  group by q.status
  order by q.status;
$function$;

create or replace function archive.requeue_dead_github_push_queue(
  p_limit integer default 100
)
returns integer
language plpgsql
as $function$
declare
  v_count integer;
begin
  with target_rows as (
    select q.id
    from archive.github_push_queue q
    where q.status = 'dead'
    order by q.id
    limit p_limit
    for update skip locked
  )
  update archive.github_push_queue q
  set status = 'pending',
      try_count = 0,
      last_error = null,
      publish_token = extensions.gen_random_uuid()
  from target_rows t
  where q.id = t.id;

  get diagnostics v_count = row_count;
  return v_count;
end;
$function$;

create or replace function archive.retry_dead_github_push_queue(
  p_requeue_limit integer default 100,
  p_process_limit integer default 20
)
returns integer
language plpgsql
as $function$
declare
  v_requeued integer;
begin
  v_requeued := archive.requeue_dead_github_push_queue(p_requeue_limit);

  if v_requeued > 0 then
    perform archive.process_github_push_queue(p_process_limit);
  end if;

  return v_requeued;
end;
$function$;

create or replace function archive.get_github_push_queue_dead_items(
  p_limit integer default 50
)
returns table(
  queue_id bigint,
  function_history_id bigint,
  schema_name text,
  function_name text,
  args text,
  return_type text,
  try_count integer,
  last_error text,
  created_at timestamptz
)
language sql
stable
as $function$
  select
    q.id,
    q.function_history_id,
    fh.schema_name,
    fh.function_name,
    fh.args,
    fh.return_type,
    q.try_count,
    q.last_error,
    q.created_at
  from archive.github_push_queue q
