with ranked as (
  select
    id,
    row_number() over (
      partition by schema_name, function_name, args, return_type, lang_settings
      order by id desc
    ) as rn
  from archive.function_history
)
update archive.function_history fh
set active = (ranked.rn = 1)
from ranked
where ranked.id = fh.id;

