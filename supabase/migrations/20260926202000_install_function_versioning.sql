  limit p_limit;
$function$;

create or replace function archive.push_updated_functions_to_github(
  p_schema text default 'public',
  p_immediate_limit integer default 40
)
returns integer
language plpgsql
as $function$
declare
  v_count integer;
begin
  insert into archive.github_push_queue(function_history_id)
  select function_history_id
  from archive.update_functions(p_schema)
  on conflict (function_history_id) do nothing;

  get diagnostics v_count = row_count;

  if p_immediate_limit > 0 then
    perform archive.process_github_push_queue(p_immediate_limit);
  end if;

  return v_count;
end;
$function$;

create or replace function archive.bootstrap_functions_to_github(
  p_schema text default 'public',
  p_immediate_limit integer default 50
)
returns integer
language plpgsql
as $function$
declare
  v_count integer;
begin
  insert into archive.github_push_queue(function_history_id)
  select id
  from archive.function_history
  where schema_name = p_schema
    and active = true
  on conflict (function_history_id) do nothing;

  get diagnostics v_count = row_count;

  if p_immediate_limit > 0 then
    perform archive.process_github_push_queue(p_immediate_limit);
  end if;

  return v_count;
end;
$function$;

create or replace function archive.push()
returns void
language plpgsql
as $function$
begin
  perform archive.push_updated_functions_to_github('archive');
  perform archive.push_updated_functions_to_github('private');
  perform archive.push_updated_functions_to_github('public');
end;
$function$;

create or replace function archive.push_cron()
returns void
language plpgsql
as $function$
begin
  perform archive.push();
end;
$function$;

