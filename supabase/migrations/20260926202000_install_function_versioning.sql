create or replace function archive.diff_text(old_text text, new_text text)
returns table(line_no integer, old_line text, new_line text)
language sql
as $function$
  select
    row_number() over ()::integer as line_no,
    o.line,
    n.line
  from regexp_split_to_table(coalesce(old_text, ''), E'\n')
    with ordinality o(line, ord)
  full join regexp_split_to_table(coalesce(new_text, ''), E'\n')
    with ordinality n(line, ord)
    using (ord)
  where o.line is distinct from n.line;
$function$;

create or replace function archive.save_function_history(
  function_name text,
  args text,
  return_type text,
  source_code text,
  schema_name text default 'public',
  lang_settings text default 'plpgsql'
)
returns void
language plpgsql
security definer
set search_path to 'public', 'archive'
as $function$
declare
  v_prev_id bigint;
  v_prev_code text;
begin
  select fh.id, fh.source_code
  into v_prev_id, v_prev_code
  from archive.function_history fh
  where fh.schema_name = save_function_history.schema_name
    and fh.function_name = save_function_history.function_name
    and fh.args = save_function_history.args
    and fh.return_type = save_function_history.return_type
    and fh.lang_settings = save_function_history.lang_settings
  order by fh.id desc
  limit 1;

  if v_prev_code is not null and not exists (
    select 1 from archive.diff_text(v_prev_code, source_code)
  ) then
    update archive.function_history fh
    set active = false
    where fh.schema_name = save_function_history.schema_name
      and fh.function_name = save_function_history.function_name
      and fh.args = save_function_history.args
      and fh.return_type = save_function_history.return_type
      and fh.lang_settings = save_function_history.lang_settings;

    update archive.function_history
    set active = true
    where id = v_prev_id;

    return;
  end if;

  update archive.function_history fh
  set active = false
  where fh.schema_name = save_function_history.schema_name
    and fh.function_name = save_function_history.function_name
    and fh.args = save_function_history.args
    and fh.return_type = save_function_history.return_type
    and fh.lang_settings = save_function_history.lang_settings;

  insert into archive.function_history (
    schema_name,
    function_name,
    args,
    return_type,
    source_code,
    lang_settings,
    active
  )
  values (
    schema_name,
    function_name,
    args,
    return_type,
    source_code,
    lang_settings,
    true
  );
end;
$function$;

create or replace function archive.update_function_history(
  function_name text,
  args text,
  return_type text,
  source_code text,
  schema_name text default 'public',
  lang_settings text default 'plpgsql'
)
returns boolean
language plpgsql
security definer
set search_path to 'public', 'archive'
as $function$
declare
  v_prev_id bigint;
  v_prev_code text;
  v_prev_active boolean;
begin
  select fh.id, fh.source_code, fh.active
  into v_prev_id, v_prev_code, v_prev_active
  from archive.function_history fh
  where fh.schema_name = update_function_history.schema_name
    and fh.function_name = update_function_history.function_name
    and fh.args = update_function_history.args
    and fh.return_type = update_function_history.return_type
    and fh.lang_settings = update_function_history.lang_settings
  order by fh.id desc
  limit 1;

  if v_prev_code is not null and not exists (
    select 1 from archive.diff_text(v_prev_code, source_code)
  ) then
    if not v_prev_active then
      update archive.function_history fh
      set active = false
      where fh.schema_name = update_function_history.schema_name
        and fh.function_name = update_function_history.function_name
        and fh.args = update_function_history.args
        and fh.return_type = update_function_history.return_type
        and fh.lang_settings = update_function_history.lang_settings;

      update archive.function_history
      set active = true
      where id = v_prev_id;
    end if;

    return false;
  end if;

  update archive.function_history fh
  set active = false
  where fh.schema_name = update_function_history.schema_name
    and fh.function_name = update_function_history.function_name
    and fh.args = update_function_history.args
    and fh.return_type = update_function_history.return_type
    and fh.lang_settings = update_function_history.lang_settings;

  insert into archive.function_history (
    schema_name,
    function_name,
    args,
    return_type,
    source_code,
    lang_settings,
    active
  )
  values (
    schema_name,
    function_name,
    args,
    return_type,
    source_code,
    lang_settings,
    true
  );

  return true;
end;
$function$;

create or replace function archive.update_functions(schema_name text default 'public')
returns table(
  function_history_id bigint,
  schema text,
  function_name text,
  args text,
  return_type text
)
language plpgsql
as $function$
declare
  function_record record;
  v_changed boolean;
  v_last_id bigint;
begin
  update archive.function_history fh
  set active = false
  where fh.schema_name = update_functions.schema_name;

  for function_record in (
    select
      n.nspname as schema_name,
      p.proname as function_name,
      pg_catalog.pg_get_function_arguments(p.oid) as args,
      pg_catalog.pg_get_function_result(p.oid) as return_type,
      pg_catalog.pg_get_functiondef(p.oid) as source_code,
      l.lanname as lang_settings
    from pg_catalog.pg_proc p
    join pg_catalog.pg_namespace n on n.oid = p.pronamespace
    join pg_catalog.pg_language l on l.oid = p.prolang
    where n.nspname = update_functions.schema_name
      and p.prokind = 'f'
  )
  loop
    v_changed := archive.update_function_history(
      function_record.function_name,
      function_record.args,
      function_record.return_type,
      function_record.source_code,
      function_record.schema_name,
      function_record.lang_settings
    );

    if v_changed then
      select fh.id
      into v_last_id
      from archive.function_history fh
      where fh.schema_name = function_record.schema_name
        and fh.function_name = function_record.function_name
        and fh.args = function_record.args
        and fh.return_type = function_record.return_type
        and fh.lang_settings = function_record.lang_settings
      order by fh.id desc
      limit 1;

      function_history_id := v_last_id;
      schema := function_record.schema_name;
      function_name := function_record.function_name;
      args := function_record.args;
      return_type := function_record.return_type;
      return next;
    end if;
  end loop;
end;
$function$;

create or replace function archive.setup_function_history(
  schema_name text default 'public'
)
returns void
language plpgsql
as $function$
declare
  function_record record;
begin
  update archive.function_history fh
  set active = false
  where fh.schema_name = setup_function_history.schema_name;

  for function_record in (
    select
      n.nspname as schema_name,
      p.proname as function_name,
      pg_catalog.pg_get_function_arguments(p.oid) as args,
      pg_catalog.pg_get_function_result(p.oid) as return_type,
      pg_catalog.pg_get_functiondef(p.oid) as source_code,
      l.lanname as lang_settings
    from pg_catalog.pg_proc p
    join pg_catalog.pg_namespace n on n.oid = p.pronamespace
    join pg_catalog.pg_language l on l.oid = p.prolang
    where n.nspname = setup_function_history.schema_name
      and p.prokind = 'f'
  )
  loop
    perform archive.save_function_history(
      function_record.function_name,
      function_record.args,
      function_record.return_type,
      function_record.source_code,
      function_record.schema_name,
      function_record.lang_settings
