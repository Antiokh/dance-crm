create function archive.get_github_push_queue_dead_items(
  p_limit integer default 50
)
returns table(
  queue_id bigint,
  item_type text,
  function_history_id bigint,
  table_history_id bigint,
  schema_name text,
  object_name text,
  try_count integer,
  last_error text,
  created_at timestamptz
)
language sql
stable
as $function$
  select
    q.id,q.item_type,q.function_history_id,q.table_history_id,
    coalesce(fh.schema_name,th.schema_name),
    coalesce(fh.function_name,th.table_name),
    q.try_count,q.last_error,q.created_at
  from archive.github_push_queue q
  left join archive.function_history fh on fh.id=q.function_history_id
  left join archive.table_history th on th.id=q.table_history_id
  where q.status='dead'
  order by q.id desc
  limit p_limit;
$function$;

create or replace function archive.push_updated_functions_to_github(
  p_schema text default 'public',
  p_immediate_limit integer default 0
)
returns integer
language plpgsql
as $function$
declare
  v_count integer;
begin
  insert into archive.github_push_queue(item_type,function_history_id)
  select 'function',function_history_id
  from archive.update_functions(p_schema)
  on conflict (function_history_id) do nothing;

  get diagnostics v_count=row_count;

  if p_immediate_limit > 0 then
    perform archive.process_github_push_queue(p_immediate_limit);
  end if;

  return v_count;
end;
$function$;

create or replace function archive.push_updated_tables_to_github(
  p_schema text default 'public',
  p_immediate_limit integer default 0
)
returns integer
language plpgsql
as $function$
declare
  v_count integer;
  v_revision_id bigint;
begin
  select count(*),max(changed.table_history_id)
  into v_count,v_revision_id
  from archive.update_tables(p_schema) changed;

  if coalesce(v_count,0) > 0 then
    insert into archive.github_push_queue(item_type,table_history_id,schema_name)
    values ('table_bundle',v_revision_id,p_schema)
    on conflict (table_history_id)
      where item_type='table_bundle'
      do nothing;
  end if;

  if p_immediate_limit > 0 then
    perform archive.process_github_push_queue(p_immediate_limit);
  end if;

  return coalesce(v_count,0);
end;
$function$;

