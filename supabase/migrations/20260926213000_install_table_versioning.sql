create or replace function archive.bootstrap_tables_to_github(
  p_schema text default 'public',
  p_immediate_limit integer default 0
)
returns integer
language plpgsql
as $function$
declare
  v_revision_id bigint;
  v_count integer;
begin
  perform archive.setup_table_history(p_schema);

  select max(th.id),count(*)
  into v_revision_id,v_count
  from archive.table_history th
  where th.schema_name=p_schema
    and th.active=true
    and th.dropped=false;

  if v_revision_id is not null then
    insert into archive.github_push_queue(item_type,table_history_id,schema_name)
    values ('table_bundle',v_revision_id,p_schema)
    on conflict (table_history_id)
      where item_type='table_bundle'
      do nothing;
  end if;

  if p_immediate_limit > 0 then
    perform archive.process_github_push_queue(p_immediate_limit);
  end if;

  return coalesce(v_count,0);
end;
$function$;

create or replace function archive.push()
returns void
language plpgsql
as $function$
begin
  perform archive.push_updated_functions_to_github('archive',0);
  perform archive.push_updated_functions_to_github('private',0);
  perform archive.push_updated_functions_to_github('public',0);

  perform archive.push_updated_tables_to_github('archive',0);
  perform archive.push_updated_tables_to_github('private',0);
  perform archive.push_updated_tables_to_github('public',0);
end;
$function$;

create or replace function archive.push_cron()
returns void
language plpgsql
as $function$
begin
  perform archive.push();
end;
$function$;

create or replace function archive.process_github_push_queue_cron(
  p_limit integer default 5
)
returns integer
language plpgsql
as $function$
begin
  return archive.process_github_push_queue(p_limit);
end;
$function$;

do $$
declare v_job_id bigint;
begin
  for v_job_id in
    select jobid from cron.job
    where jobname in (
      'archive-function-push',
      'archive-versioning-scan',
      'archive-github-push-queue'
    )
  loop
    perform cron.unschedule(v_job_id);
  end loop;
end
$$;

select cron.schedule(
  'archive-versioning-scan',
  '*/10 * * * *',
  $$select archive.push_cron();$$
);

