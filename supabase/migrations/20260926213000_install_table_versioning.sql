create or replace function public.get_table_publish_payload(
  p_table_history_id bigint,
  p_publish_token uuid
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
  v_schema_name text;
  v_payload jsonb;
begin
  if not exists (
    select 1
    from archive.github_push_queue q
    where q.item_type='table_bundle'
      and q.table_history_id=p_table_history_id
      and q.publish_token=p_publish_token
      and q.status='pending'
      and q.try_count < 10
  ) then
    raise exception 'invalid or inactive table publish token'
      using errcode='42501';
  end if;

  select q.schema_name
  into v_schema_name
  from archive.github_push_queue q
  where q.item_type='table_bundle'
    and q.table_history_id=p_table_history_id;

  if v_schema_name is null then
    raise exception 'table bundle queue row not found'
      using errcode='P0002';
  end if;

  select jsonb_build_object(
    'schema', v_schema_name,
    'tables', coalesce(
      jsonb_agg(
        jsonb_build_object(
          'table_name', th.table_name,
          'ddl', archive.redact_function_source(th.ddl)
        )
        order by th.table_name
      ),
      '[]'::jsonb
    )
  )
  into v_payload
  from archive.table_history th
  where th.schema_name=v_schema_name
    and th.active=true
    and th.dropped=false;

  return v_payload;
end;
$function$;

revoke all on function public.get_table_publish_payload(bigint, uuid)
from public, anon, authenticated;
grant execute on function public.get_table_publish_payload(bigint, uuid)
to service_role;

create or replace function archive.github_send_tables(
  p_table_history_id bigint
)
returns void
language plpgsql
as $function$
declare
  v_publish_token uuid;
  v_edge_base_url text;
  v_response extensions.http_response;
  v_body jsonb;
begin
  select q.publish_token
  into v_publish_token
  from archive.github_push_queue q
  where q.item_type='table_bundle'
    and q.table_history_id=p_table_history_id
    and q.status='pending';

  if v_publish_token is null then
    raise exception 'pending table bundle queue item not found';
  end if;

  select edge_base_url
  into v_edge_base_url
  from archive.function_versioning_settings
  where singleton=true;

  if v_edge_base_url is null then
    raise exception 'function versioning edge_base_url is not configured';
  end if;

  v_response := extensions.http((
    'POST',
    rtrim(v_edge_base_url, '/') || '/github-send',
    array[extensions.http_header('Content-Type','application/json')],
    'application/json',
    jsonb_build_object(
      'table_history_id', p_table_history_id,
      'publish_token', v_publish_token
    )::text
  )::extensions.http_request);

  if v_response.status < 200 or v_response.status >= 300 then
    raise exception 'github-send HTTP %: %',
      v_response.status,
      left(coalesce(v_response.content,''),1000);
  end if;

  v_body := v_response.content::jsonb;

  if coalesce((v_body->>'ok')::boolean,false) is not true then
    raise exception 'github-send table bundle failed: %',
      coalesce(v_body->>'error',v_response.content);
  end if;
end;
$function$;

create or replace function archive.process_github_push_queue(
  p_limit integer default 5
)
returns integer
language plpgsql
as $function$
declare
  r record;
  v_count integer := 0;
begin
  for r in
    select id,item_type,function_history_id,table_history_id,try_count
    from archive.github_push_queue
    where status='pending'
      and try_count < 10
    order by id
    limit greatest(p_limit,0)
    for update skip locked
  loop
    begin
      if r.item_type='function' then
        perform archive.github_send_function(r.function_history_id);
      elsif r.item_type='table_bundle' then
        perform archive.github_send_tables(r.table_history_id);
      else
        raise exception 'unsupported queue item type: %', r.item_type;
      end if;

      update archive.github_push_queue
      set status='done',
          pushed_at=now(),
          last_error=null
      where id=r.id;

      v_count := v_count+1;
    exception when others then
      update archive.github_push_queue
      set try_count=try_count+1,
          last_error=SQLERRM,
          status=case when try_count+1 >= 10 then 'dead' else 'pending' end
      where id=r.id;
    end;
  end loop;

  return v_count;
end;
$function$;

