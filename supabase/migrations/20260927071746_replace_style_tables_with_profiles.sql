           coalesce(t.is_trainer, false),
           true,
           t.created_at,
           t.created_at
         from public.%I t
         join public.dancer d on d.id = t.id
         where coalesce(t.main_role, d.primary_role) in (1, 2)
         on conflict (dancer_id, style_id, is_leader) do update
         set is_trainer = public.dancer_style_profile.is_trainer or excluded.is_trainer,
             is_default = true',
        v_style.id,
        v_style.table_name
      );
    else
      execute format(
        'insert into public.dancer_style_profile (
           dancer_id,
           style_id,
           is_leader,
           is_trainer,
           is_default,
           created_at,
           updated_at
         )
         select
           t.id,
           %s::smallint,
           coalesce(t.main_role, d.primary_role) = 1,
           false,
           true,
           t.created_at,
           t.created_at
         from public.%I t
         join public.dancer d on d.id = t.id
