
create table public.styles_levels (
  id bigint generated by default as identity primary key,
  style_id smallint not null references public.l_dance_style(id) on delete cascade,
  code text not null,
  title_en text not null,
  title_ru text,
  title_sr text,
  rank_order smallint not null default 0,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (style_id, code),
  unique (id, style_id)
);

alter table public.styles_levels enable row level security;

grant select on public.styles_levels to anon, authenticated;

create policy styles_levels_read_active
on public.styles_levels
for select
to anon, authenticated
using (active);

create table public.dancer_style_profile (
  id uuid primary key default extensions.gen_random_uuid(),
  dancer_id uuid not null references public.dancer(id) on delete cascade,
  style_id smallint not null references public.l_dance_style(id) on delete cascade,
  is_leader boolean not null,
  is_trainer boolean not null default false,
  is_default boolean not null default false,
  level_id bigint,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (dancer_id, style_id, is_leader),
  foreign key (level_id, style_id)
    references public.styles_levels(id, style_id)
    on delete set null
);

